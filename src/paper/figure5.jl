module Figure5
using ..AmpDefInc
using CairoMakie
using LaTeXStrings
using Statistics



const FIG_DIR = OUTPUT_ROOT
const NUMERICAL_DIR = joinpath(DATA_ROOT, "numerical")
const MEAN_FREQUENCY_FILE = joinpath(NUMERICAL_DIR, "K_continuation_mean_frequency.csv")
const MIN_RADIUS_FILE = joinpath(NUMERICAL_DIR, "K_continuation_min_radius.csv")
const ORDER_PARAMETER_FILE = joinpath(NUMERICAL_DIR, "K_continuation_order_parameters.csv")
const ORDER_BASE_TYPOGRAPHY_TEST = lowercase(get(ENV, "BASE_TYPOGRAPHY_TEST", "false")) == "true"
const ORDER_TYPOGRAPHY_TEST_SUFFIX = ORDER_BASE_TYPOGRAPHY_TEST ? "_base_typography_test" : ""
const FREQUENCY_COMPARISON_OUTPUT_STEM = joinpath(FIG_DIR, "Fig_omegak_Omega_order_parameters_instantaneous_vs_mean_frequency_Rfreq" * ORDER_TYPOGRAPHY_TEST_SUFFIX)
const FIG5_OUTPUT_STEM = joinpath(FIG_DIR, "Fig_5" * ORDER_TYPOGRAPHY_TEST_SUFFIX)
const USE_MEAN_FREQUENCY_R = true # Matches the archived Fig_5 output.
const COMPARE_FREQUENCY_R = false

const K_VALUE = 0.880
# Transition values generated by plot_fig_2_k_cont_ill_cont.jl.
const K_HB = 0.963
const K_DEF = 0.948
const LOW_CLUSTER_THRESHOLD = 0.7
const LATEX_BASE_PT = 24.0
const LATEX_FIGURE_WIDTH_PT = 6.5 * 72.0
const FIGURE_SIZE_PT = (LATEX_FIGURE_WIDTH_PT, 1.45 * LATEX_FIGURE_WIDTH_PT)
const TICK_PT = 1.00 * LATEX_BASE_PT
const LABEL_PT = 1.00 * LATEX_BASE_PT
const TITLE_PT = 1.00 * LATEX_BASE_PT
const LINE_PT = 1.90
const ORDER_MARKER_PT = 5.4
const FREQUENCY_MARKER_PT = 3.4

const BLUE = RGBf(0.0, 0.20, 0.65)
const RED = RGBf(0.84, 0.22, 0.13)
const GREEN = RGBf(0.0, 0.50, 0.24)
const PURPLE = RGBf(0.48, 0.20, 0.68)

const PAPER_FONT = AmpDefInc.PAPER_FONT

function read_mean_frequency_csv(path::AbstractString)
    lines = readlines(path)
    header = split(lines[1], ",")
    header[2] == "system_mean_frequency" || error("Expected system_mean_frequency in the second column.")
    omega = Float64[]
    for label in header[3:end]
        m = match(r"omega_([-+0-9.eE]+)$", label)
        m === nothing && error("Could not parse omega from CSV header label: $label")
        push!(omega, parse(Float64, m.captures[1]))
    end

    k_values = Float64[]
    mean_frequency = Matrix{Float64}(undef, length(lines) - 1, length(omega))
    for (i, line) in enumerate(lines[2:end])
        parts = split(line, ",")
        push!(k_values, parse(Float64, parts[1]))
        for j in eachindex(omega)
            mean_frequency[i, j] = parse(Float64, parts[j + 2])
        end
    end
    return k_values, omega, mean_frequency
end

function read_order_parameter_csv(path::AbstractString)
    lines = readlines(path)
    header = split(lines[1], ",")
    columns = Dict(name => i for (i, name) in pairs(header))
    required = ("K", "R_high_mean", "R_low_mean", "Rfreq_low_mean")
    for name in required
        haskey(columns, name) || error("Missing column $name in $(basename(path)).")
    end

    values = Dict(name => Float64[] for name in required)
    for line in lines[2:end]
        parts = split(line, ",")
        for name in required
            push!(values[name], parse(Float64, parts[columns[name]]))
        end
    end
    return (;
        K = values["K"],
        R_high_mean = values["R_high_mean"],
        R_low_mean = values["R_low_mean"],
        Rfreq_low_mean = values["Rfreq_low_mean"],
    )
end

function read_min_radius_csv(path::AbstractString)
    lines = readlines(path)
    header = split(lines[1], ",")
    omega = Float64[]
    for label in header[2:end]
        m = match(r"omega_([-+0-9.eE]+)$", label)
        m === nothing && error("Could not parse omega from CSV header label: $label")
        push!(omega, parse(Float64, m.captures[1]))
    end

    k_values = Float64[]
    min_radius = Matrix{Float64}(undef, length(lines) - 1, length(omega))
    for (i, line) in enumerate(lines[2:end])
        parts = split(line, ",")
        push!(k_values, parse(Float64, parts[1]))
        for j in eachindex(omega)
            min_radius[i, j] = parse(Float64, parts[j + 1])
        end
    end
    return k_values, omega, min_radius
end

function mean_frequency_order_parameter(mean_frequency, min_radius, omega)
    size(mean_frequency) == size(min_radius) || error("Mean-frequency and minimum-radius arrays do not match.")
    values = fill(NaN, size(mean_frequency, 1))

    for row in axes(mean_frequency, 1)
        low_indices = findall((@view min_radius[row, :]) .< LOW_CLUSTER_THRESHOLD)
        valid_indices = [idx for idx in low_indices if isfinite(mean_frequency[row, idx]) && isfinite(omega[idx])]
        length(valid_indices) >= 2 || continue

        intrinsic_variance = var(omega[valid_indices]; corrected = false)
        mean_frequency_variance = var(mean_frequency[row, valid_indices]; corrected = false)
        values[row] = iszero(intrinsic_variance) ?
                      (mean_frequency_variance <= 1.0e-14 ? 1.0 : 0.0) :
                      max(1.0 - mean_frequency_variance / intrinsic_variance, 0.0)
    end
    return values
end

function style_axis!(ax)
    ax.xgridvisible = true
    ax.ygridvisible = true
    ax.xgridcolor = (:black, 0.09)
    ax.ygridcolor = (:black, 0.09)
    ax.xticklabelsize = TICK_PT
    ax.yticklabelsize = TICK_PT
    ax.xlabelsize = LABEL_PT
    ax.ylabelsize = LABEL_PT
    ax.titlesize = TITLE_PT
    ax.spinewidth = 0.85
    ax.xtickwidth = 0.85
    ax.ytickwidth = 0.85
    ax.xticksize = 2.8
    ax.yticksize = 2.8
    ax.xlabelpadding = 2.0
    ax.ylabelpadding = 2.0
    ax.xticklabelpad = 2.0
    ax.yticklabelpad = 2.0
    return ax
end

function nearest_row(k_values, K)
    idx = argmin(abs.(k_values .- Float64(K)))
    abs(k_values[idx] - Float64(K)) <= 1.0e-8 || @warn "Using nearest K=$(k_values[idx]) for requested K=$K"
    return idx
end

function add_series!(ax, K, y; color, label, linestyle = :solid)
    lines!(ax, K, y; color, linewidth = LINE_PT, label, linestyle)
    scatter!(ax, K, y; color, markersize = ORDER_MARKER_PT)
end

function panel_label!(ax, label; position = (0.025, 0.97), align = (:left, :top))
    text!(
        ax,
        position...;
        text = label,
        space = :relative,
        align,
        fontsize = TITLE_PT,
        font = :bold,
        color = :black,
    )
    return ax
end

function main()
    k_values, omega, mean_frequency = read_mean_frequency_csv(MEAN_FREQUENCY_FILE)
    frequency_row = nearest_row(k_values, K_VALUE)
    mean_frequency_at_k = mean_frequency[frequency_row, :]
    finite_frequency = mean_frequency_at_k[isfinite.(mean_frequency_at_k)]
    frequency_limits = extrema(finite_frequency)
    frequency_padding = 0.05 * max(frequency_limits[2] - frequency_limits[1], eps())
    omega_limits = extrema(omega)
    omega_padding = 0.05 * max(omega_limits[2] - omega_limits[1], eps())

    order_data = read_order_parameter_csv(ORDER_PARAMETER_FILE)
    frequency_order_parameter = order_data.Rfreq_low_mean
    mean_frequency_R = nothing
    frequency_order_parameter_label = L"R^{\mathrm{freq}}_{\mathrm{low}}"
    output_stem = FIG5_OUTPUT_STEM

    if USE_MEAN_FREQUENCY_R || COMPARE_FREQUENCY_R
        min_radius_K, min_radius_omega, min_radius = read_min_radius_csv(MIN_RADIUS_FILE)
        min_radius_K == k_values || error("Mean-frequency and minimum-radius K grids do not match.")
        min_radius_omega == omega || error("Mean-frequency and minimum-radius omega grids do not match.")
        order_data.K == k_values || error("Order-parameter and mean-frequency K grids do not match.")
        mean_frequency_R = mean_frequency_order_parameter(mean_frequency, min_radius, omega)
        if USE_MEAN_FREQUENCY_R
            frequency_order_parameter = mean_frequency_R
            frequency_order_parameter_label = L"R^{\mathrm{mean\,freq}}_{\mathrm{low}}"
            output_stem = FIG5_OUTPUT_STEM
        else
            output_stem = FREQUENCY_COMPARISON_OUTPUT_STEM
        end
    end

    fig = Figure(
        size = FIGURE_SIZE_PT,
        backgroundcolor = :white,
        figure_padding = (0.22 * LATEX_BASE_PT, 0.22 * LATEX_BASE_PT, 0.22 * LATEX_BASE_PT, 0.20 * LATEX_BASE_PT),
        fonts = (; regular = PAPER_FONT, bold = PAPER_FONT, italic = PAPER_FONT, bold_italic = PAPER_FONT),
        fontsize = LATEX_BASE_PT,
    )

    frequency_ax = Axis(
        fig[2, 1];
        xlabel = L"\omega_k",
        ylabel = L"\Omega_k",
        limits = (
            omega_limits[1] - omega_padding,
            omega_limits[2] + omega_padding,
            frequency_limits[1] - frequency_padding,
            frequency_limits[2] + frequency_padding,
        ),
    )
    style_axis!(frequency_ax)
    scatter!(frequency_ax, omega, mean_frequency_at_k; color = (:black, 0.50), markersize = FREQUENCY_MARKER_PT)
    panel_label!(frequency_ax, "(b)")

    order_ax = Axis(
        fig[1, 1];
        xlabel = L"K",
        ylabel = "order parameter",
        limits = (minimum(order_data.K), maximum(order_data.K), -0.03, 1.03),
    )
    style_axis!(order_ax)
    order_ax.xticks = (
        [0.85, 0.90, K_DEF, K_HB],
        [L"0.85", L"0.90", L"K_{\mathrm{def}}", L"K_{\mathrm{HB}}"],
    )
    # Draw transition markers first so every order-parameter curve remains visible on top.
    vlines!(order_ax, [K_HB]; color = :black, linestyle = :dot, linewidth = 1.15 * LINE_PT)
    vlines!(order_ax, [K_DEF]; color = :black, linestyle = :dashdot, linewidth = 1.15 * LINE_PT)
    add_series!(order_ax, order_data.K, order_data.R_high_mean; color = BLUE, label = L"R_{\mathrm{high}}")
    add_series!(order_ax, order_data.K, order_data.R_low_mean; color = RED, label = L"R_{\mathrm{low}}")
    if COMPARE_FREQUENCY_R
        add_series!(order_ax, order_data.K, order_data.Rfreq_low_mean; color = GREEN, label = L"R^{\mathrm{inst}}_{\mathrm{low}}", linestyle = :dash)
        add_series!(order_ax, order_data.K, mean_frequency_R; color = PURPLE, label = L"R^{\mathrm{mean}}_{\mathrm{low}}", linestyle = :dot)
    else
        add_series!(order_ax, order_data.K, frequency_order_parameter; color = GREEN, label = frequency_order_parameter_label, linestyle = :dash)
    end
    axislegend(
        order_ax;
        position = :lt,
        framevisible = false,
        labelsize = 0.80 * LABEL_PT,
        patchsize = (1.20 * LATEX_BASE_PT, 0.55 * LATEX_BASE_PT),
        rowgap = 0.20 * LATEX_BASE_PT,
    )
    panel_label!(order_ax, "(a)"; position = (0.975, 0.97), align = (:right, :top))

    rowgap!(fig.layout, 0.45 * LATEX_BASE_PT)

    png_path = output_stem * ".png"
    pdf_path = output_stem * ".pdf"
    save(png_path, fig; px_per_unit = 3)
    save(pdf_path, fig)
    if USE_MEAN_FREQUENCY_R && !COMPARE_FREQUENCY_R
        fig5_png_path = FIG5_OUTPUT_STEM * ".png"
        fig5_pdf_path = FIG5_OUTPUT_STEM * ".pdf"
        @info "Saved combined omega/Omega and order-parameter plot" png_path pdf_path fig5_png_path fig5_pdf_path K_value=k_values[frequency_row] mean_frequency_Rfreq=USE_MEAN_FREQUENCY_R compare_frequency_Rfreq=COMPARE_FREQUENCY_R
    else
        @info "Saved combined omega/Omega and order-parameter plot" png_path pdf_path K_value=k_values[frequency_row] mean_frequency_Rfreq=USE_MEAN_FREQUENCY_R compare_frequency_Rfreq=COMPARE_FREQUENCY_R
    end
end


end
